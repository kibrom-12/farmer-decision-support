# ------------------------------------------------------------

# We use log scale because some crops have many more observations
# than others.

crop_support["support_score"] = (
    np.log1p(crop_support["historical_records"])
    / np.log1p(crop_support["historical_records"].max())
    * 100
)

# ------------------------------------------------------------
# 3. Use the latest candidate ranking
# ------------------------------------------------------------

confidence_table = recommendations.copy()

# Add historical support
confidence_table = confidence_table.merge(
    crop_support,
    left_on="crop",
    right_on="s4q01b",
    how="left"
)

confidence_table = confidence_table.drop(
    columns=["s4q01b"]
)

# ------------------------------------------------------------
# 4. Calculate prediction margin
# ------------------------------------------------------------

# Difference between this crop and the next crop
confidence_table["next_predicted_kg"] = (
    confidence_table["predicted_harvest_kg"]
    .shift(-1)
)

confidence_table["margin_kg"] = (
    confidence_table["predicted_harvest_kg"]
    - confidence_table["next_predicted_kg"]
)

# Relative margin is more useful than raw kg
confidence_table["relative_margin_pct"] = (
    confidence_table["margin_kg"]
    / confidence_table["predicted_harvest_kg"].replace(0, np.nan)
    * 100
)

# Last-ranked crop has no next crop
confidence_table["relative_margin_pct"] = (
    confidence_table["relative_margin_pct"]
    .fillna(0)
)

# ------------------------------------------------------------
# 5. Rank confidence
# ------------------------------------------------------------

# Cap the margin contribution so one unusually large
# prediction cannot dominate the score.

margin_score = (
    confidence_table["relative_margin_pct"]
    .clip(lower=0, upper=100)
)

# ------------------------------------------------------------
# 6. Preliminary recommendation strength
# ------------------------------------------------------------

confidence_table["recommendation_strength"] = (
    0.60 * confidence_table["support_score"]
    + 0.40 * margin_score
)

