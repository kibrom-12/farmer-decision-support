# Negative harvest values are invalid
yield_check.loc[
    yield_check["harvest_kg_clean"] < 0,
    "harvest_kg_clean"
] = np.nan


# ------------------------------------------------------------
# 2. ESTIMATE CROP AREA
# ------------------------------------------------------------

# s4q03 = approximate percentage of field planted with crop
# s3q08 = GPS-recorded field area, treated as square meters
#
# crop area (m²) = field GPS area × crop percentage / 100
# crop area (ha) = crop area (m²) / 10,000

yield_check["crop_area_m2"] = (
    yield_check["s3q08"] *
    yield_check["s4q03"] / 100
)

yield_check["crop_area_ha"] = (
    yield_check["crop_area_m2"] / 10000
)


# ------------------------------------------------------------
# 3. CALCULATE YIELD
# ------------------------------------------------------------

yield_check["yield_kg_ha"] = (
    yield_check["harvest_kg_clean"] /
    yield_check["crop_area_ha"]
)

# Remove invalid mathematical results
yield_check.loc[
    ~np.isfinite(yield_check["yield_kg_ha"]),
    "yield_kg_ha"
] = np.nan


# ------------------------------------------------------------
# 4. REMOVE VERY SMALL CROP AREAS
# ------------------------------------------------------------

# Minimum reliable crop area:
# 0.0005 ha ≈ 5 m²

area_filter = (
    yield_check["crop_area_ha"] >= 0.0005
)

valid_before_area_filter = yield_check[
    yield_check["yield_kg_ha"].notna()
].copy()

yield_area_clean = yield_check[
    area_filter &
    yield_check["yield_kg_ha"].notna() &
    (yield_check["yield_kg_ha"] >= 0)
].copy()


# ------------------------------------------------------------
# 5. CROP-SPECIFIC OUTLIER DETECTION
# ------------------------------------------------------------

yield_area_clean["log_yield"] = np.log1p(
    yield_area_clean["yield_kg_ha"]
)

crop_stats = (
    yield_area_clean
    .groupby("s4q01b")["log_yield"]
    .agg(
        q1=lambda x: x.quantile(0.25),
        q3=lambda x: x.quantile(0.75)
    )
    .reset_index()
)

crop_stats["iqr"] = (
    crop_stats["q3"] -
    crop_stats["q1"]
)

crop_stats["upper_fence"] = (
    crop_stats["q3"] +
    1.5 * crop_stats["iqr"]
)

yield_area_clean = yield_area_clean.merge(
    crop_stats[
        ["s4q01b", "upper_fence"]
    ],
    on="s4q01b",
    how="left"
)

