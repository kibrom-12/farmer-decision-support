def forecast_rainfall_7days():

    # Use the most recent historical observations
    history = rainfall_history.copy().sort_values("time").reset_index(drop=True)

    working = history.copy()

    predictions = []

    for step in range(7):

        last_date = working["time"].iloc[-1]
        next_date = last_date + pd.Timedelta(days=1)

        # Historical temporal features
        row = {}

        row["temperature_2m_mean"] = working["temperature_2m_mean"].iloc[-1]
        row["temperature_2m_max"] = working["temperature_2m_max"].iloc[-1]
        row["temperature_2m_min"] = working["temperature_2m_min"].iloc[-1]

        row["day_of_year"] = next_date.dayofyear
        row["month"] = next_date.month

        row["sin_day"] = np.sin(
            2 * np.pi * next_date.dayofyear / 365.25
        )

        row["cos_day"] = np.cos(
            2 * np.pi * next_date.dayofyear / 365.25
        )

        # Rainfall lags
        for lag in [1, 2, 3, 7, 14, 21, 28]:
            row[f"rain_lag_{lag}"] = (
                working["rain_sum"].iloc[-lag]
            )

        # Rolling rainfall
        for window in [3, 7, 14, 28]:
            row[f"rain_roll_{window}"] = (
                working["rain_sum"].iloc[-window:].sum()
            )

        # Temperature lags
        for lag in [1, 7, 14]:
            row[f"temp_lag_{lag}"] = (
                working["temperature_2m_mean"].iloc[-lag]
            )

        X_next = pd.DataFrame([row])[rain_features]

        # AI prediction is on log scale
        pred_log = rain_model.predict(X_next)[0]

        predicted_rain = max(
            0,
            np.expm1(pred_log)
        )

        predictions.append({
            "Date": next_date.strftime("%Y-%m-%d"),
            "Forecast Rainfall (mm)": round(predicted_rain, 2)
        })

        # Add prediction back so the next day can use it
        new_row = working.iloc[-1].copy()

        new_row["time"] = next_date
        new_row["rain_sum"] = predicted_rain

        working = pd.concat(
            [working, pd.DataFrame([new_row])],
            ignore_index=True
        )

    forecast_df = pd.DataFrame(predictions)

    return forecast_df


# ------------------------------------------------------------
