# ------------------------------------------------------------

def rainfall_risk_from_forecast(forecast_df):

    total_rain = forecast_df[
        "Forecast Rainfall (mm)"
    ].sum()

    rainy_days = (
        forecast_df["Forecast Rainfall (mm)"] > 1
    ).sum()

    heavy_days = (
        forecast_df["Forecast Rainfall (mm)"] >= 10
    ).sum()

    # Demo decision thresholds
    if total_rain < 5:
        dryness_risk = 80
    elif total_rain < 15:
        dryness_risk = 50
    else:
        dryness_risk = 20

    if heavy_days >= 2:
        excess_rain_risk = 80
    elif heavy_days == 1:
        excess_rain_risk = 50
    else:
        excess_rain_risk = 20

    probability_factor = 40

    risk_score = (
        0.45 * dryness_risk +
        0.35 * excess_rain_risk +
        0.20 * probability_factor
    )

    if risk_score < 35:
        level = "Low"
    elif risk_score < 55:
        level = "Moderate"
    elif risk_score < 75:
        level = "High"
    else:
        level = "Very High"

    return (
        round(risk_score, 1),
        level,
        round(total_rain, 2),
        int(rainy_days),
        int(heavy_days)
    )


