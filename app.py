def calculate_rainfall_risk_from_input(rain_7day):
    """
    Farm-level rainfall risk based on the same rule-based
    thresholds used in the current system.
    """

    if rain_7day < 5:
        dryness_risk = 80
    elif rain_7day < 15:
        dryness_risk = 50
    else:
        dryness_risk = 20

    # For farmer-entered total rainfall we don't know
    # the number of heavy-rain days, so use a neutral factor.
    excess_rain_risk = 20

    probability_risk = 40

    risk_score = (
        0.45 * dryness_risk +
        0.35 * excess_rain_risk +
        0.20 * probability_risk
    )

    if risk_score < 35:
        risk_level = "Low"
    elif risk_score < 55:
        risk_level = "Moderate"
    elif risk_score < 75:
        risk_level = "High"
    else:
        risk_level = "Very High"

    return risk_score, risk_level


