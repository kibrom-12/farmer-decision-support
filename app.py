# 8. RAINFALL RISK
# ============================================================

def calculate_ai_rainfall_risk(forecast):

    total_rain = forecast[
        "AI Rainfall Forecast (mm)"
    ].sum()

    rainy_days = (
        forecast[
            "AI Rainfall Forecast (mm)"
        ] > 1
    ).sum()

    heavy_days = (
        forecast[
            "AI Rainfall Forecast (mm)"
        ] >= 10
    ).sum()

    if total_rain < 5:
        dryness_risk = 80
    elif total_rain < 15:
        dryness_risk = 50
    else:
        dryness_risk = 20

    if heavy_days >= 2:
        excess_risk = 80
    elif heavy_days == 1:
        excess_risk = 50
    else:
        excess_risk = 20

    max_probability = forecast[
        "Rain Probability (%)"
    ].max()

    if max_probability >= 75:
        probability_risk = 20
    elif max_probability >= 50:
        probability_risk = 40
    else:
        probability_risk = 60

    risk_score = (
        0.45 * dryness_risk +
        0.35 * excess_risk +
        0.20 * probability_risk
    )

    if risk_score < 35:
        level = "Low"
    elif risk_score < 55:
        level = "Moderate"
    elif risk_score < 75:
        level = "High"
    else:
        level = "Very High"

    return (
        round(risk_score, 1),
        level,
        round(total_rain, 2),
        int(rainy_days),
        int(heavy_days)
    )


