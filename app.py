# 7. Confidence category
# ------------------------------------------------------------

def confidence_category(score):

    if score >= 70:
        return "High"

    elif score >= 45:
        return "Medium"

    else:
        return "Low"


confidence_table["confidence"] = (
    confidence_table["recommendation_strength"]
    .apply(confidence_category)
)

