# 7. AI 7-DAY FORECAST
# ============================================================

def ai_rainfall_forecast():

    history = rain_history_final.copy()

    results = []

    for step in range(7):

        next_date = (
            history["time"].iloc[-1]
            + pd.Timedelta(days=1)
        )

        row = {}

        row["day_of_year"] = next_date.dayofyear
        row["month"] = next_date.month

        row["sin_day"] = np.sin(
            2 * np.pi *
            next_date.dayofyear / 365.25
        )

        row["cos_day"] = np.cos(
            2 * np.pi *
            next_date.dayofyear / 365.25
        )

        # Rainfall lags
        for lag in [1, 2, 3, 7, 14, 21, 28]:
            row[f"rain_lag_{lag}"] = (
                history["rain_sum"].iloc[-lag]
            )

        # Temperature lags
        for lag in [1, 7, 14]:
            row[f"temp_lag_{lag}"] = (
                history[
                    "temperature_2m_mean"
                ].iloc[-lag]
            )

        # Rolling rainfall
        for window in [3, 7, 14, 28]:
            row[f"rain_roll_{window}"] = (
                history[
                    "rain_sum"
                ].iloc[-window:].sum()
            )

        X_next = pd.DataFrame(
            [row]
        )[rain_ai_features]

        # Probability of rain
        rain_probability = (
            rain_event_model
            .predict_proba(X_next)[0, 1]
        )

        # AI rainfall amount
        predicted_log_amount = (
            rain_amount_model
            .predict(X_next)[0]
        )

        predicted_amount = max(
            0,
            np.expm1(
                predicted_log_amount
            )
        )

        # Threshold avoids unrealistic tiny drizzle
        if rain_probability < 0.30:
            predicted_rain = 0.0
        else:
            predicted_rain = predicted_amount

        results.append({
            "Date":
                next_date.strftime("%Y-%m-%d"),

            "Rain Probability (%)":
                round(
                    rain_probability * 100,
                    1
                ),

            "AI Rainfall Forecast (mm)":
                round(
                    predicted_rain,
                    2
                )
        })

        # Add prediction for recursive forecasting
        new_row = history.iloc[-1].copy()

        new_row["time"] = next_date
        new_row["rain_sum"] = predicted_rain

        history = pd.concat(
            [
                history,
                pd.DataFrame([new_row])
            ],
            ignore_index=True
        )

    return pd.DataFrame(results)


